def a(n):
    return P[n][0], P[n][1] + W * 0.14


def amap(arrows="", area2="Area 2", area2_tone="g", extra=""):
    """Карта трёх областей: Area 1 — Area 0 — Area 2, с ABR между ними и ASBR в Area 2."""
    base = (blob(230, 310, 200, 210, "p", "Area 1", seed=.4, lab_y=86, fs=20) +
            blob(600, 300, 175, 200, "b", "Area 0", seed=1.3, lab_y=86, fs=20) +
            blob(965, 310, 200, 210, area2_tone, area2, seed=2.2, lab_y=86, fs=20) +
            globe(1150, 500, 32, "#6b4fd0") + txt(1150, 552, "внешняя сеть", fs=15, weight=800) +
            "".join(link(*(a(x) + a(y)), w=4, color="#7d9cc0") for x, y in LINKS) +
            link(1080, 418, 1125, 485, 4, "#7d9cc0", dash="8 6") +
            "".join(router(x, y, W, TN[n], label=n) for n, (x, y) in P.items()))
    return ill("0 0 1200 580", base + arrows + extra)


def lab(x, y, text, tone):
    return pill(x, y, text, tone, 15, h=30)


