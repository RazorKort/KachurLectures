    xl, xr = 130, 660
    b += txt(xl, 22, "ПК-1", 12, "middle", "#17213a", 780)
    b += txt(xr, 22, "сервер ВКонтакте", 12, "middle", "#17213a", 780)
    b += wire(xl, 32, xl, 330, "rgba(120,135,165,.4)", 1.6, "5 5")
    b += wire(xr, 32, xr, 330, "rgba(120,135,165,.4)", 1.6, "5 5")
    msgs = [
        (1, 60, "SEQ=1", "сегмент 1 · 1460 Б", PAL["l7"], True),
        (1, 86, "SEQ=1461", "сегмент 2 · 1460 Б", PAL["l7"], True),
        (1, 112, "SEQ=2921", "сегмент 3 · 1460 Б", PAL["l7"], True),
        (2, 150, "ACK=2921", "первые два приняты", PAL["green"], False),
        (3, 190, "сегмент 3 потерян", "кадр не прошёл проверку FCS на коммутаторе", PAL["red"], None),
        (4, 230, "ACK=2921", "дублирующее подтверждение — «жду 2921»", PAL["amber"], False),
        (5, 270, "SEQ=2921", "повтор сегмента 3", PAL["l7"], True),
        (6, 310, "ACK=4381", "всё на месте, окно поехало дальше", PAL["green"], False),
    ]
    for st, y, name, sub, col, right in msgs:
        if right is None:
            g = box(xl + 60, y - 14, 410, 30, "rgba(226,80,75,.09)", PAL["red"], 8, 1.3)
            g += txt(xl + 265, y + 1, name + " — " + sub, 10.5, "middle", "#b4322d", 720)
        else:
            x1, x2 = (xl, xr) if right else (xr, xl)
            g = arrow(x1 + (10 if right else -10), y, x2 - (10 if right else -10), y, col, 2)
            g += txt((xl + xr) / 2, y - 8, name + " · " + sub, 10.5, "middle", col, 700, mono=True)
        b += '<g class="fade" data-s="%d">%s</g>' % (st, g)
    return svg(800, 346, b, -10, 0)


