    o.append('<path d="M80 240H560" stroke="%s" stroke-width="2" opacity=".5" marker-end="url(#ah)"/>' % S.SOFT)
    o.append('<path d="M80 240V40" stroke="%s" stroke-width="2" opacity=".5" marker-end="url(#ah)"/>' % S.SOFT)
    o.append(S.txt(320, 268, "число устройств в домене", 13, S.SOFT, 700))
    o.append(S.txt(26, 140, "полезная", 12, S.SOFT, 700, extra=' transform="rotate(-90 26 140)"'))
    o.append(S.txt(44, 140, "пропускная способность", 12, S.SOFT, 700,
                   extra=' transform="rotate(-90 44 140)"'))
    o.append('<path d="M90 70Q240 90 330 150T540 225" stroke="%s" stroke-width="4" fill="none"/>' % S.RD)
    o.append('<circle cx="90" cy="70" r="6" fill="%s"/>' % S.LM)
    o.append('<circle cx="540" cy="225" r="6" fill="%s"/>' % S.RD)
    o.append(S.txt(150, 56, "мало устройств — коллизий почти нет", 12.5, S.LM, 700, "start"))
    o.append(S.txt(540, 205, "сеть «задыхается»", 12.5, S.RD, 700, "end"))
