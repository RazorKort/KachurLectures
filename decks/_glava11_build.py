def arrowhead(x, y, ang, cls):
    a = math.radians(ang)
    p = [(x, y), (x - 14 * math.cos(a) + 7 * math.sin(a), y - 14 * math.sin(a) - 7 * math.cos(a)),
         (x - 14 * math.cos(a) - 7 * math.sin(a), y - 14 * math.sin(a) + 7 * math.cos(a))]
    return f'<polygon class="{cls}" points="{" ".join(f"{u:.1f},{v:.1f}" for u, v in p)}"/>'

