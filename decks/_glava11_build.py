    d = f"M{x1} {(ytop+ybot)/2}"; x = x1; up = True; y = (ytop + ybot) / 2; first = True
    while x < x2:
        nx = min(x2, x + (per / 2 if first else per)); first = False
        d += f" L{nx} {ytop if up else ybot}"; up = not up; x = nx
    return d
