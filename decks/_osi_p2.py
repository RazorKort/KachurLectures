def tcp_scene() -> str:
    b = defs()
    xl, xr = 120, 640
    b += txt(xl, 24, "ПК-1 · 192.168.10.25", 12, "middle", "#17213a", 780)
    b += txt(xr, 24, "Сервер · 192.168.10.10", 12, "middle", "#17213a", 780)
    b += wire(xl, 36, xl, 330, "rgba(120,135,165,.4)", 1.6, "5 5")
    b += wire(xr, 36, xr, 330, "rgba(120,135,165,.4)", 1.6, "5 5")
    msgs = [
        (1, 70, "SYN", "SEQ=0 · порт 49312 → 80 · окно 64240 · MSS 1460", PAL["l4"], True),
        (2, 130, "SYN, ACK", "SEQ=0 · ACK=1 · окно 29200 · MSS 1460", PAL["l4"], False),
        (3, 190, "ACK", "SEQ=1 · ACK=1 — соединение установлено", PAL["green"], True),
        (4, 250, "PSH, ACK", "первые 1460 байт файла", PAL["l7"], True),
        (5, 300, "ACK", "ACK=1461 — получил, шлю следующее", PAL["green"], False),
    ]
    for st, y, name, sub, col, right in msgs:
        x1, x2 = (xl, xr) if right else (xr, xl)
        g = arrow(x1 + (12 if right else -12), y, x2 - (12 if right else -12), y, col, 2.2)
        g += txt((xl + xr) / 2, y - 10, name, 12, "middle", col, 800, mono=True)
        g += txt((xl + xr) / 2, y + 16, sub, 10, "middle", PAL["dim"], 620)
        b += '<g class="fade" data-s="%d">%s</g>' % (st, g)
    b += ('<g class="fade" data-s="3">%s</g>'
          % txt(xl - 100, 196, "сокет 192.168.10.25:49312", 10, "start", PAL["l4"], 700, mono=True))
    return svg(800, 346, b, -10, 0)


