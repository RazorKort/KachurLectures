def wave_scene() -> str:
    b = defs()
    pattern = "10110010"
    x0, w, hi, lo = 90, 86, 60, 118
    b += txt(6, 26, "Байт 0xB2 = 10110010 — так его видит сетевая карта", 11.5, "start", "#17213a", 740)
    # биты сверху
    for i, ch in enumerate(pattern):
        b += ('<g class="fade" data-s="%d">%s%s</g>'
              % (1,
                 box(x0 + i * w, 36, w - 4, 22, "rgba(59,130,246,.08)", "rgba(59,130,246,.3)", 5, 1),
                 txt(x0 + i * w + (w - 4) / 2, 52, ch, 13, "middle",
                     PAL["l3"] if ch == "1" else PAL["dim"], 800, mono=True)))
    # NRZ
    d = "M%d %d" % (x0, lo if pattern[0] == "0" else hi)
    prev = pattern[0]
    for i, ch in enumerate(pattern):
        lvl = hi if ch == "1" else lo
        if ch != prev:
            d += " V%d" % lvl
        d += " H%d" % (x0 + (i + 1) * w)
        prev = ch
    b += ('<g class="fade" data-s="2">%s%s%s</g>'
          % (txt(6, 92, "NRZ", 11, "start", PAL["l1"], 780),
             '<path d="%s" stroke="%s" stroke-width="2.6" fill="none"/>' % (d, PAL["l1"]),
             txt(6, 108, "1 = +U, 0 = 0 В", 9.5, "start", PAL["dim"], 600)))
    # Манчестер
    mhi, mlo = 168, 226
    d2 = ""
    for i, ch in enumerate(pattern):
        xa = x0 + i * w
        xm = xa + w / 2
        xb = xa + w
        a, bb = (mhi, mlo) if ch == "1" else (mlo, mhi)
        d2 += " M%s %s H%s V%s H%s" % (xa, a, xm, bb, xb)
    b += ('<g class="fade" data-s="3">%s%s%s</g>'
          % (txt(6, 200, "Манчестер", 11, "start", PAL["l2"], 780),
             '<path d="%s" stroke="%s" stroke-width="2.6" fill="none"/>' % (d2, PAL["l2"]),
             txt(6, 216, "переход в середине бита", 9.5, "start", PAL["dim"], 600)))
    for i in range(len(pattern) + 1):
        b += wire(x0 + i * w, 36, x0 + i * w, 240, "rgba(120,135,165,.22)", 1, "3 4")
    b += ('<g class="fade" data-s="4">%s%s</g>'
          % (box(x0, 256, w * 8 - 4, 44, "rgba(122,134,153,.1)", PAL["l1"], 10, 1.3),
             txt(x0 + (w * 8) / 2, 283, "Гигабитный Ethernet: 1 бит ≈ 1 нс. Кадр 1518 байт = "
                 "12 144 бита ≈ 12 мкс в проводе", 11.5, "middle", "#17213a", 700)))
    return svg(810, 312, b, -4, 0)


