def enc_scene() -> str:
    b = defs()
    b += txt(10, 18, "Отправитель: сверху вниз, каждый уровень дописывает свой заголовок",
             11.5, "start", "#17213a", 740)
    b += lvl_stack(10, 32, 232, 34, None, 1, "enc")
    rows = [
        ("Данные файла", [("d7", "отчёт.xlsx · 1 800 000 байт")], 1),
        ("L7 HTTP/SMB", [("h7-", "")], 2),
    ]
    # PDU-полоски справа
    x0, w0 = 288, 700
    y0 = 42
    seq = [
        (1, [("Данные приложения", PAL["l7"], 1.0)]),
        (2, [("HTTP-заголовок", PAL["l7"], .30), ("данные", PAL["l7"], .70)]),
        (3, [("шифрование TLS", PAL["l6"], .26), ("HTTP + данные", PAL["l7"], .74)]),
        (4, [("сессия", PAL["l5"], .18), ("TLS + HTTP + данные", PAL["l7"], .82)]),
        (5, [("TCP", PAL["l4"], .17), ("сегмент данных ≤ 1460 Б", PAL["l7"], .83)]),
        (6, [("IP", PAL["l3"], .15), ("TCP", PAL["l4"], .15), ("данные", PAL["l7"], .70)]),
        (7, [("Ethernet", PAL["l2"], .18), ("IP", PAL["l3"], .13), ("TCP", PAL["l4"], .13),
             ("данные", PAL["l7"], .46), ("FCS", PAL["l2"], .10)]),
    ]
    names = ["Данные", "Данные + HTTP", "Данные (шифр)", "Сеанс", "Сегмент", "Пакет (датаграмма)", "Кадр"]
    for i, (st, parts) in enumerate(seq):
        yy = y0 + i * 34
        g = ""
        cx = x0
        for label, col, frac in parts:
            ww = w0 * frac
            g += box(cx, yy, ww - 3, 29, col + "22", col, 7, 1.3)
            g += txt(cx + ww / 2 - 1, yy + 18.5, label, 10, "middle", "#17213a", 700)
            cx += ww
        g += txt(x0 - 12, yy + 18.5, names[i], 10, "end", PAL["dim"], 700)
        b += '<g class="fade" data-s="%d">%s</g>' % (st, g)
    b += ('<g class="fade" data-s="7">%s%s</g>'
          % (box(x0, y0 + 7 * 34 + 6, w0 - 3, 30, "rgba(122,134,153,.12)", PAL["l1"], 7, 1.3),
             txt(x0 + (w0 - 3) / 2, y0 + 7 * 34 + 25, "L1: 12 176 бит в проводе — импульсы напряжения, "
                 "преамбула, манчестерское / 4B5B-кодирование", 10, "middle", "#17213a", 700)))
    return svg(1010, 300, b)


