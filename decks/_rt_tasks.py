def fld(tid, k, label, ok, width="13rem", ph=""):
    return (f'<label class="tfl"><span>{rich(label)}</span>'
            f'<input id="{tid}-{k}" data-ok="{ok}" placeholder="{ph}" autocomplete="off" spellcheck="false" style="width:{width}"></label>')


def chk(tid, k, label, ok=False):
    o = ' data-ok="1"' if ok else ''
    return f'<label class="tck"><input type="checkbox" id="{tid}-{k}"{o}><span>{rich(label)}</span></label>'


def task(tid, body, fields, solution, nfo=""):
    return (f'<div class="tsk" id="{tid}" data-s="1">{body}'
            f'<div class="tfs">{fields}</div>'
            f'<div class="row trow"><button type="button" class="btn on" data-a="check">Проверить</button>'
            f'<button type="button" class="btn" data-a="sol">Показать решение</button>'
            f'<button type="button" class="btn" data-a="clr">Очистить</button>'
            f'<span class="qzc">{nfo}</span></div>'
            f'<div class="tmsg" aria-live="polite"></div>'
            f'<div class="tsol" hidden>{solution}</div></div>')


