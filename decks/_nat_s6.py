def _pool(x, y, states, ph=None):
    o = ['<g%s>' % (' data-ph="%d"' % ph if ph is not None else "")]
    o.append(S.box(x, y, 250, 140, S.CY, "rgba(5,18,46,.96)", 12, 1.8))
    o.append(S.txt(x + 125, y + 26, "Пул адресов NAT", 16, S.CY, 900))
    for i, (ip, st, sph) in enumerate(states):
        yy = y + 54 + i * 28
        o.append(S.txt(x + 20, yy, ip, 15, "#fff", 800, "start", True))
        o.append('<g data-ph-upto="%d" data-ph="0">' % (sph - 1 if sph else 99))
        o.append(S.txt(x + 230, yy, "Not Use", 14, S.GR, 800, "end") + '</g>')
        if sph:
            o.append('<g data-ph="6">' + S.txt(x + 230, yy, "Not Use", 14, S.GR, 800, "end") + '</g>')
            o.append('<g data-ph="%d" data-ph-upto="5">' % sph + '<rect x="%g" y="%g" width="234" height="24" rx="5" fill="none" stroke="%s" stroke-width="2"/>'
                     % (x + 8, yy - 18, S.YE) + S.txt(x + 230, yy, "In Use", 14, S.RD, 800, "end") + '</g>')
    o.append('</g>')
    return "".join(o)


