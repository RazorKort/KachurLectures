def _scene_dhcp_params():
    """Инфографика «DHCP для IPv4»: сервер раздаёт четыре параметра устройствам."""
    o = []
    params = [("IPv4-адрес", "y"), ("Маска подсети", "o"), ("DNS-сервер", "v"), ("Шлюз по умолчанию", "g")]
    o.append(S.server(600, 300, "DHCP-сервер", "раздаёт параметры", 150))
    devs = [(150, 170, "ПК"), (1050, 170, "Ноутбук"), (150, 440, "Ноутбук 2"), (1050, 440, "Принтер")]
    for i, (x, y, nm) in enumerate(devs):
        if nm == "ПК":
            o.append(S.pc(x, y, nm, "", 90))
        elif nm == "Принтер":
            o.append(S.dev("sd-pc", x, y, 80, "Принтер", "статический адрес", S.OR))
        else:
            o.append(S.laptop(x, y + 20, nm, "", .95))
        o.append(S.link(600 + (-90 if x < 600 else 90), 300, x + (70 if x < 600 else -70), y, S.CY, 2, .35, True))
    # параметры по шагам вылетают к первому ПК, затем ко всем
    for k, (nm, t) in enumerate(params):
        o.append(S.chip(400 if k < 2 else 610, 70 + (k % 2) * 46, k + 1, nm, t, 200 if k < 2 else 250, ph=1))
    for i, (x, y, nm) in enumerate(devs[:3]):
        o.append(S.env(600, 300, x + (110 if x < 600 else -110), y - 30, "IP · маска · DNS · шлюз", 2 + i, S.YE, True, 210))
    o.append(S.badge(1050, 520, "Принтеру адрес задан вручную", S.OR, ph=5, size=14))
    o.append(S.note(330, 470, ["Устройства получают параметры", "автоматически — меньше ручных", "ошибок и нагрузки на администратора"],
                    S.LM, ph=5, w=340))
    return scene(S.fig("".join(o)), [
        "<b>DHCP-сервер</b> в центре сети, вокруг — клиенты без настроек.",
        "Сервер хранит <b>4 параметра</b>: IPv4-адрес, маску, DNS-сервер и шлюз по умолчанию.",
        "Компьютер подключился — получает свой набор параметров.",
        "Ноутбук — тоже автоматически.",
        "Ещё один ноутбук — из того же пула, но с другим адресом.",
        "Итог: <b>динамическая</b> адресация для клиентов, <b>статическая</b> — для принтеров и серверов.",
    ])


def _scene_principle():
    o = []
    o.append(S.laptop(150, 300, "DHCP-клиент", "любое устройство в сети", 1.3))
    o.append(S.server(1040, 260, "DHCP-сервер", "маршрутизатор или сервер", 150))
    rows = [("DHCPDISCOVER", "Клиент ищет DHCP-сервер", "y", 1), ("DHCPOFFER", "Сервер предлагает адрес", "o", 2),
            ("DHCPREQUEST", "Клиент выбирает предложение", "v", 3), ("DHCPACK", "Сервер подтверждает адрес", "g", 4)]
    for i, (nm, d, t, ph) in enumerate(rows):
        y = 120 + i * 82
        right = i % 2 == 0
        o.append('<g data-ph="%d">' % ph)
        o.append(S.chip(330, y, i + 1, nm, t, 470))
        o.append(S.txt(565, y + 58, d, 14, S.SOFT, 700))
        c = S.TONE[t]
        if right:
            o.append('<path d="M290 %dH930" stroke="%s" stroke-width="3" marker-end="url(#mk%s)" class="flow"/>' % (y + 19, c, t))
        else:
            o.append('<path d="M930 %dH290" stroke="%s" stroke-width="3" marker-end="url(#mk%s)" class="flow"/>' % (y + 19, c, t))
        o.append('</g>')
    # пул
    o.append(S.box(870, 400, 300, 140, S.LM, "rgba(5,18,46,.95)"))
    o.append(S.txt(1020, 424, "Пул адресов", 15, S.LM, 800))
    for j, a in enumerate(["192.168.1.100", "192.168.1.101", "192.168.1.102", "…  192.168.1.200"]):
        hl = ' data-ph="4"' if j == 1 else ""
        o.append('<g%s><rect x="890" y="%d" width="260" height="22" rx="5" fill="rgba(108,240,138,.2)"/></g>' % (hl, 436 + j * 25))
        o.append(S.txt(1020, 452 + j * 25, a, 14, "#fff", 700, mono=True))
    o.append(S.badge(150, 470, "получил 192.168.1.101", S.GR, ph=4, size=15))
    return scene(S.fig("".join(o)), [
        "При подключении узел ещё <b>не имеет адреса</b>. Сервер хранит <b>пул адресов</b>.",
        "<b>DHCPDISCOVER</b> — клиент ищет любой DHCP-сервер в сети.",
        "<b>DHCPOFFER</b> — сервер предлагает свободный адрес из пула.",
        "<b>DHCPREQUEST</b> — клиент сообщает, что принимает предложение.",
        "<b>DHCPACK</b> — сервер подтверждает: адрес 192.168.1.101 выдан клиенту.",
    ])
