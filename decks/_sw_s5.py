def _scene_vlan_why():
    o = []
    names = ["1/0/1", "1/0/2", "1/0/3", "1/0/4", "1/0/5", "1/0/6"]
    sw, pts = S.switch(330, 250, 540, 82, 6, "Коммутатор L2 без VLAN", names=names)
    o.append(sw)
    PCS = [(110, 60, "10.10.1.5", S.CY), (110, 400, "10.10.1.6", S.LM),
           (1090, 60, "10.10.1.7", S.MG), (1090, 400, "10.10.1.8", S.AM)]
    for (x, y, ip, c) in PCS:
        o.append(S.pc(x, y, ip, col=c))
        o.append(S.link(x, y + (100 if y < 250 else -16), 600, 290, S.SOFT, 2, .22))

    o.append(S.badge(600, 180, "10.10.1.5 хочет узнать MAC-адрес устройства 10.10.1.6", S.CY, ph=1, only=True))
    o.append(S.pkt(200, 140, 350, 250, "ARP: кто имеет 10.10.1.6?", 1, S.RD, w=250,
                   sub="DMAC ff:ff:ff:ff:ff:ff"))
    for (x, y, ip, c) in PCS[1:]:
        o.append(S.arrow(600, 290, x, y + (100 if y < 250 else -10), S.RD, 3.2, "ahr", ph=2))
    o.append(S.badge(600, 180, "Запрос получат ВСЕ устройства сегмента L2", S.RD, ph=2, only=True))
    o.append(S.note(280, 430, [
        "Даже те, которые не предназначены для получения рассылки, обязаны",
        "прочитать кадр и сравнить Target IP со своим адресом.",
        "Это приводит к перегрузке и снижению пропускной способности всей сети."], S.RD, ph=3, w=640, only=True))
    o.append(S.badge(600, 180, "А если таких устройств 200—300?", S.AM, ph=4, only=True))
    o.append(S.note(280, 430, [
        "Решение — разделить сеть на несколько широковещательных доменов.",
        "Физически — дорого. Логически — это и есть VLAN."], S.LM, ph=4, w=640, only=True))

    caps = ["Один коммутатор, четыре узла, один широковещательный домен",
            "Узел 10.10.1.5 отправляет ARP-запрос",
            "Запрос разлетается по всем портам",
            "Цена вопроса для сети",
            "Как это решается"]
    return scene(S.fig("".join(o)), caps)


def _scene_tag_fields():
    o = []
    o.append(S.frame_strip(70, 70, [("Preamble", 5, S.SOFT), ("SFD", 2, S.SOFT), ("DMAC", 6, S.CY),
                                    ("SMAC", 6, S.MG), ("802.1Q", 5, S.AM),
                                    ("EtherType", 5, S.LM), ("Данные", 12, S.SOFT),
                                    ("FCS", 3, S.RD)],
                           w=1060, h=46, cap="Тегированный кадр Ethernet"))
    o.append('<path d="M668 118L560 180" stroke="%s" stroke-width="2" opacity=".6"/>' % S.AM)
    o.append('<path d="M780 118L1040 180" stroke="%s" stroke-width="2" opacity=".6"/>' % S.AM)

    # разворот тега
    X0, W = 160, 880
    FIELDS = [("TPID\n16 бит", 16, S.AM), ("PRI\n3", 3, S.CY), ("CFI\n1", 1, S.MG), ("VLAN ID\n12 бит", 12, S.LM)]
    tot = float(sum(f[1] for f in FIELDS))
    cx = X0
    for i, (nm, share, c) in enumerate(FIELDS):
        fw = W * share / tot
        o.append('<g data-ghost="%d"><rect x="%g" y="200" width="%g" height="72" rx="8" fill="rgba(10,30,70,.88)" stroke="%s" stroke-width="2.2"/>'
                 % (i + 2, cx + 3, fw - 6, c))
        parts = nm.split("\n")
        for k, t in enumerate(parts):
            o.append(S.txt(cx + fw / 2.0, 230 + k * 20, t, 14 if k == 0 else 12, c, 800))
        o.append("</g>")
        o.append('<rect data-ph="%d" data-ph-only x="%g" y="194" width="%g" height="84" rx="11" fill="none" stroke="%s" stroke-width="3.4" filter="url(#gl)"/>'
                 % (i + 1, cx, fw, c))
        cx += fw
    o.append(S.txt(600, 182, "Метка 802.1Q — 32 бита между Source MAC и EtherType", 14, S.SOFT, 700))

    DESC = [
        ("Метка целиком", [
            "Протокол 802.1Q добавляет к заголовку Ethernet два поля по 16 бит,",
            "итого 32 бита (4 байта). Из-за них максимум кадра растёт до 1522 байт."], S.AM),
        ("TPID — Tag Protocol ID, 16 бит", [
            "Идентификатор протокола тегирования.",
            "Для 802.1Q здесь всегда 0x8100 (1000 0001 0000 0000).",
            "Увидев это значение, устройство понимает: дальше идёт TCI."], S.AM),
        ("PRI / PCP — 3 бита", [
            "Priority Code Point — используется протоколом 802.1p.",
            "Задаёт приоритет кадра от 0 до 7.",
            "По нему голос и видео обгоняют обычные данные в очередях."], S.CY),
        ("CFI / DEI — 1 бит", [
            "Исторически Canonical Format Indicator — признак формата MAC-адреса",
            "для совместимости Ethernet и Token Ring.",
            "В современных сетях — DEI, признак кадра, которым можно пожертвовать."], S.MG),
        ("VLAN ID — 12 бит", [
            "Главная часть метки: именно по ней определяется принадлежность",
            "к той или иной виртуальной сети. Значения от 1 до 4095.",
            "VLAN 1 и VLAN 4095 на Eltex зарезервированы."], S.LM),
    ]
    for i, (t, lines, c) in enumerate(DESC):
        o.append(S.note(240, 330, [t] + lines, c, ph=i, w=720, only=True))

    caps = ["Метка 802.1Q целиком — 32 бита",
            "<b>TPID</b> — идентификатор протокола тегирования",
            "<b>PRI</b> — приоритет кадра по 802.1p",
            "<b>CFI / DEI</b> — служебный бит",
            "<b>VLAN ID</b> — номер виртуальной сети"]
    return scene(S.fig("".join(o)), caps)


