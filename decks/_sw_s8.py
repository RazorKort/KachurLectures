def _qslide(title, sub, qs):
    slide(title, sc(
        head(title.replace("Тест", "<em>Тест</em>"), sub),
        grow("g2", col(*qs[:2]), col(*qs[2:])),
        '<div class="foot" style="margin-top:8px"><i>✓</i><span>Результат: <span class="score">0 / 0</span></span></div>'
    ))


