def graph(marks=None, visited=(), active=None, tree=(), hot=(), lab_cls=None, edge_cls=None):
    """Граф методички. marks: {'R2':'8'}; tree: [('R1','R2'),…] — жёлтые рёбра."""
    marks = marks or {}
    lab_cls = lab_cls or {}
    edge_cls = edge_cls or {}
    out = []
    for (a, b, w) in GE:
        x1, y1 = GP[a]
        x2, y2 = GP[b]
        key = a + b
        isTree = (a, b) in tree or (b, a) in tree
        isHot = key in hot or (b + a) in hot
        col_ = "#ffd93d" if isTree else ("#ff5c9e" if isHot else "#c7d6e4")
        wd = 9 if isTree else (8 if isHot else 5)
        out.append(link(x1, y1, x2, y2, w=wd, color=col_, cls=edge_cls.get(key, "")))
    for (a, b, w) in GE:
        x1, y1 = GP[a]
        x2, y2 = GP[b]
        mx, my = (x1 + x2) / 2.0, (y1 + y2) / 2.0
        out.append('<circle cx="%.0f" cy="%.0f" r="17" fill="#fff" stroke="#c7d6e4" stroke-width="2"/>' % (mx, my))
        out.append(txt(mx, my + 5, str(w), fs=14))
    for n, (x, y) in GP.items():
        if n in visited:
            fillc, ink = "#3fc47c", "#fff"
        elif n == active:
            fillc, ink = "#ffd93d", "#121212"
        elif n in marks:
            fillc, ink = "#ffd3e4", "#121212"
        else:
            fillc, ink = "#eef2f6", "#121212"
        if n == active:
            out.append('<circle class="dhalo go-f" cx="%.0f" cy="%.0f" r="54" fill="#ffd93d" opacity=".35"/>' % (x, y))
        out.append('<circle cx="%.0f" cy="%.0f" r="36" fill="%s" stroke="#121212" stroke-width="3"/>' % (x, y, fillc))
        out.append(txt(x, y - 4, n, fs=17, color=ink, weight=900))
        m = marks.get(n, "∞")
        out.append('<text class="%s" x="%.0f" y="%.0f" text-anchor="middle" font-size="15" '
                   'font-weight="800" fill="%s">%s</text>' % (lab_cls.get(n, ""), x, y + 16, ink, m))
    return "".join(out)


